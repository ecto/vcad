/// A nested type that can expand itself into a JSON Schema fragment,
/// used by `#[tool(expand)]` fields to give the AI a full view of the
/// allowed shape instead of an opaque `{"type":"object"}` fallback.
///
/// Typically implemented by hand for `#[serde(tag = "type")]` enums,
/// returning a `{"oneOf": [...]}` schema that enumerates each variant.
pub trait SubToolSchema {
    /// Return a JSON Schema fragment describing this type.
    fn sub_schema() -> serde_json::Value;
}

/// A tool schema entry generated by the ToolSchema derive macro.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[cfg_attr(feature = "ts-rs", derive(ts_rs::TS))]
#[cfg_attr(feature = "ts-rs", ts(export, export_to = "bindings/"))]
pub struct ToolSchemaEntry {
    /// Variant name in snake_case (e.g. "cube", "extrude").
    pub name: String,
    /// Description from doc comments.
    pub description: String,
    /// Category (e.g. "primitive", "sketch_op", "modifier").
    pub category: String,
    /// Optional AI hint for the system prompt.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    #[cfg_attr(feature = "ts-rs", ts(optional))]
    pub ai_hint: Option<String>,
    /// JSON Schema for the variant's fields.
    #[cfg_attr(feature = "ts-rs", ts(type = "unknown"))]
    pub input_schema: serde_json::Value,
}


/// A declarative edge selector, resolved against the current topology at
/// evaluation time. Queries express intent ("the edge near this corner",
/// "all vertical edges") instead of fragile indices, so selections survive
/// regeneration after upstream parameter changes.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(tag = "type")]
#[cfg_attr(feature = "ts-rs", derive(ts_rs::TS))]
#[cfg_attr(feature = "ts-rs", ts(export, export_to = "bindings/"))]
pub enum EdgeQuery {
    /// Every plane-plane manifold edge of the solid.
    All,
    /// The single edge whose nearest endpoint is closest to `point`; that
    /// endpoint becomes the start of a keyed profile.
    Near {
        /// Selection point in model space.
        point: Vec3,
    },
    /// Edges whose direction lies within `tol_deg` degrees of `axis`
    /// (sign ignored) — e.g. `axis = +Z` selects vertical edges.
    Direction {
        /// Reference direction.
        axis: Vec3,
        /// Angular tolerance in degrees.
        tol_deg: f64,
    },
    /// The edge between two persistently named faces (topological naming).
    ///
    /// Face names are `scope:tag[.n]*` — the scope is `n<nodeId>` of the
    /// generating primitive (e.g. `n1:top`, `n1:right`); primitives seed
    /// tags from the generating operation (`top`/`bottom`/`front`/`back`/
    /// `left`/`right` for a box, `side`+caps for a cylinder), and booleans
    /// propagate them with deterministic split ordinals. Unlike the
    /// geometric queries, resolution is fail-closed: an ambiguous or lost
    /// reference is an evaluation error, never a nearest-edge guess.
    Named {
        /// Name of one adjacent face.
        face_a: String,
        /// Name of the other adjacent face.
        face_b: String,
    },
}


// Bundles the curated orderable electronic parts DB (lib/parts/orderable.json
// — the source of truth, same lib/-data pattern as mechanical.json) into a
// TypeScript module so tsc emits it into dist/ and esbuild inlines it.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = join(pkgDir, "..", "..", "lib", "parts", "orderable.json");
const raw = readFileSync(srcPath, "utf-8");

const db = JSON.parse(raw);
const where = "lib/parts/orderable.json";
if (db.schema !== "vcad-orderable-parts/1") {
  throw new Error(`${where}: unexpected schema "${db.schema}" (expected vcad-orderable-parts/1)`);
}
if (!Array.isArray(db.parts) || db.parts.length === 0) throw new Error(`${where}: no parts`);
const STATUSES = new Set(["verified", "corrected", "flagged"]);
const ids = new Set();
for (const p of db.parts) {
  if (!p.id || !p.category || !p.footprint || typeof p.pins !== "number") {
    throw new Error(`${where}: malformed entry ${JSON.stringify(p.id ?? p)}`);
  }
  if (!STATUSES.has(p.verification?.status)) {
    throw new Error(`${where}: ${p.id} has bad verification.status`);
  }
  if (p.lcsc != null && !/^C\d+$/.test(p.lcsc)) throw new Error(`${where}: ${p.id} bad lcsc "${p.lcsc}"`);
  if (ids.has(p.id)) throw new Error(`${where}: duplicate id "${p.id}"`);
  ids.add(p.id);
}

const out = `// Generated by scripts/gen-orderable-catalog.mjs from lib/parts/orderable.json — do not edit.
/* eslint-disable */
/** Curated orderable parts DB (schema vcad-orderable-parts/1), bundled at build time. */
export const ORDERABLE_CATALOG_JSON: string = ${JSON.stringify(JSON.stringify(db))};
`;
writeFileSync(join(pkgDir, "src", "tools", "orderable-catalog.generated.ts"), out);
console.log(`[gen-orderable-catalog] embedded ${db.parts.length} parts`);

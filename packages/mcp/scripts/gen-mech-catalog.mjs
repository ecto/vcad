// Bundles the curated mechanical COTS catalog (lib/parts/mechanical.json —
// the source of truth, same lib/-data pattern as the DFM rule packs) into a
// TypeScript module so tsc emits it into dist/ and esbuild (Vercel bundle)
// inlines it — no runtime file reads, which break after bundling relocates
// the module.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const pkgDir = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcPath = join(pkgDir, "..", "..", "lib", "parts", "mechanical.json");
const raw = readFileSync(srcPath, "utf-8");

// Parse + re-serialize: fail loudly on malformed JSON at build time, and
// emit a canonical compact form so the bundle doesn't carry formatting.
const catalog = JSON.parse(raw);
if (catalog.schema !== "vcad-mech-catalog/1") {
  throw new Error(
    `lib/parts/mechanical.json: unexpected schema "${catalog.schema}" (expected vcad-mech-catalog/1)`,
  );
}
if (!Array.isArray(catalog.parts) || catalog.parts.length === 0) {
  throw new Error("lib/parts/mechanical.json: no parts");
}
const ids = new Set();
for (const p of catalog.parts) {
  if (!p.id || !p.type || !p.name || !p.spec || !Array.isArray(p.price_band_usd)) {
    throw new Error(`lib/parts/mechanical.json: malformed entry ${JSON.stringify(p.id ?? p)}`);
  }
  if (ids.has(p.id)) throw new Error(`lib/parts/mechanical.json: duplicate id "${p.id}"`);
  ids.add(p.id);
}

const out = `// Generated by scripts/gen-mech-catalog.mjs from lib/parts/mechanical.json — do not edit.
/* eslint-disable */
/** Curated mechanical COTS catalog (schema vcad-mech-catalog/1), bundled at build time. */
export const MECH_CATALOG_JSON: string = ${JSON.stringify(JSON.stringify(catalog))};
`;

writeFileSync(join(pkgDir, "src", "tools", "mech-catalog.generated.ts"), out);
console.log(
  `[gen-mech-catalog] embedded ${catalog.parts.length} parts (${(raw.length / 1024).toFixed(1)} KB source)`,
);

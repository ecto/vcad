#!/usr/bin/env node
// Generate the per-task reference images referenced from `inputs[]`.
//
// For every task JSON in mecheval/tasks/ whose structured inputs declare
// `reference_image` entries with `image_kind: "render"`, this script
// renders the task's grader-side geometry (`host_geometry` for Suite F,
// `target_mesh` for Suite D) from the declared view (front/side/top/hero)
// via the `vcad-render` binary and writes the JPEG to the declared path.
//
// F3/F4 tasks additionally get a hero.jpg (3/4 view) next to their host,
// per mecheval/tasks/assets/README.md, even when no input references it.
//
// Real photographs (`image_kind: "photo"`) are never touched — those are
// captured, not generated.
//
// Usage:
//   node mecheval/scripts/render-task-assets.mjs [--only <task-id>[,<task-id>...]]
//
// The render binary is resolved from $VCAD_RENDER_BIN, then
// target/release/vcad-render, then target/debug/vcad-render; if none
// exists, `cargo build -p vcad-render` is run first.

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const tasksDir = join(repoRoot, "mecheval", "tasks");

const VIEWS = new Set(["front", "side", "top", "hero"]);
const RENDER_ARGS = ["--size", "1024", "--fill", "0.6", "--quality", "92"];

function parseArgs(argv) {
  const out = { only: null };
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--only") {
      out.only = new Set((argv[++i] ?? "").split(",").filter(Boolean));
    } else {
      console.error(`unknown flag: ${argv[i]}`);
      process.exit(2);
    }
  }
  return out;
}

function findRenderBin() {
  const candidates = [
    process.env.VCAD_RENDER_BIN,
    join(repoRoot, "target", "release", "vcad-render"),
    join(repoRoot, "target", "debug", "vcad-render"),
  ].filter(Boolean);
  for (const c of candidates) {
    if (existsSync(c)) return c;
  }
  console.error("vcad-render binary not found; running `cargo build -p vcad-render`...");
  execFileSync("cargo", ["build", "-p", "vcad-render"], {
    cwd: repoRoot,
    stdio: "inherit",
  });
  return join(repoRoot, "target", "debug", "vcad-render");
}

function geometryInput(task) {
  const inputs = (task.inputs ?? []).filter((i) => typeof i === "object");
  return (
    inputs.find((i) => i.kind === "host_geometry" && i.path) ??
    inputs.find((i) => i.kind === "target_mesh" && i.path)
  );
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const bin = findRenderBin();

  let rendered = 0;
  let skippedPhotos = 0;
  const failures = [];

  const taskFiles = readdirSync(tasksDir)
    .filter((f) => f.endsWith(".json"))
    .sort();

  for (const file of taskFiles) {
    const task = JSON.parse(readFileSync(join(tasksDir, file), "utf8"));
    if (args.only && !args.only.has(task.id)) continue;

    const refs = (task.inputs ?? []).filter(
      (i) => typeof i === "object" && i.kind === "reference_image" && i.path,
    );
    if (refs.length === 0) continue;

    const geom = geometryInput(task);
    const jobs = [];
    for (const ref of refs) {
      if (ref.image_kind === "photo") {
        skippedPhotos++;
        if (!existsSync(resolve(tasksDir, ref.path))) {
          console.warn(`${task.id}: photo input ${ref.path} is missing (not generated by this script)`);
        }
        continue;
      }
      if (!VIEWS.has(ref.view)) {
        failures.push(`${task.id}: unknown view '${ref.view}' for ${ref.path}`);
        continue;
      }
      jobs.push({ view: ref.view, out: resolve(tasksDir, ref.path) });
    }

    // F3/F4 ship a hero.jpg per assets/README.md even when no input
    // references it yet.
    if (/^F[34]$/.test(task.tier ?? "") && geom && !jobs.some((j) => j.view === "hero")) {
      jobs.push({ view: "hero", out: resolve(tasksDir, dirname(geom.path), "hero.jpg") });
    }

    if (jobs.length === 0) continue;
    if (!geom) {
      failures.push(`${task.id}: no host_geometry/target_mesh input to render from`);
      continue;
    }
    const geomPath = resolve(tasksDir, geom.path);
    if (!existsSync(geomPath)) {
      failures.push(`${task.id}: geometry file missing: ${geom.path}`);
      continue;
    }

    for (const job of jobs) {
      try {
        execFileSync(bin, [geomPath, "--view", job.view, "--jpeg", job.out, ...RENDER_ARGS], {
          stdio: ["ignore", "inherit", "pipe"],
        });
        console.log(`${task.id}: ${job.view} -> ${job.out.replace(repoRoot + "/", "")}`);
        rendered++;
      } catch (e) {
        failures.push(`${task.id}: ${job.view} failed: ${e.stderr?.toString().trim() || e.message}`);
      }
    }
  }

  console.log(`\nrendered ${rendered} image(s), skipped ${skippedPhotos} photo input(s)`);
  if (failures.length > 0) {
    console.error(`\n${failures.length} failure(s):`);
    for (const f of failures) console.error(`  ${f}`);
    process.exit(1);
  }
}

main();
